#!/usr/bin/env node
// sw-manifest.mjs — writes the service worker's integrity manifest into
// public/sw.js (the block between the GENERATED markers): the SHA-256 of every
// static asset the worker may ever serve from its cache, and the security
// headers it re-applies to such a response (src/lib/http.js SECURITY_HEADERS,
// the same values as public/_headers). The worker serves a cached copy only
// when its body has exactly the hash listed here (SECURITY.md, "Service worker
// and install banner").
//
//   node tools/sw-manifest.mjs           # rewrite the block
//   node tools/sw-manifest.mjs --check   # exit 1 when the block is out of date
//
// Run it after any change to public/css, public/js, public/fonts, public/img,
// public/index.html, public/manifest.webmanifest or public/favicon.ico
// (test-node/sw.test.js fails while the block is stale).
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SECURITY_HEADERS } from '../src/lib/http.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const PUBLIC = join(ROOT, 'public');
const SW = join(PUBLIC, 'sw.js');
const BEGIN = '// ── GENERATED by tools/sw-manifest.mjs: do not edit by hand ──';
const END = '// ── end of GENERATED ──';

/** Every file below `dir` (sorted, forward slashes, relative to public/). */
function filesUnder(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...filesUnder(p));
    else out.push(relative(PUBLIC, p).split(sep).join('/'));
  }
  return out;
}

/** The manifest: URL path → base64 SHA-256 of the body served for it. */
export function buildManifest() {
  const entries = [['/', 'index.html']];
  for (const f of ['manifest.webmanifest', 'favicon.ico']) entries.push([`/${f}`, f]);
  for (const d of ['css', 'fonts', 'img', 'js']) for (const f of filesUnder(join(PUBLIC, d))) entries.push([`/${f}`, f]);
  const manifest = {};
  for (const [path, file] of entries.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))) {
    manifest[path] = createHash('sha256').update(readFileSync(join(PUBLIC, file))).digest('base64');
  }
  return manifest;
}

/** The generated block (the manifest and the headers), as sw.js source. */
export function generatedBlock() {
  const m = buildManifest();
  const lines = Object.entries(m).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  const h = Object.entries(SECURITY_HEADERS).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  return [
    BEGIN,
    '// The SHA-256 (base64) of each static asset this build serves: a cached copy is used only with this exact body.',
    'const ASSET_SHA256 = Object.freeze({',
    ...lines,
    '});',
    '// The security headers re-applied to a response served from the cache (src/lib/http.js SECURITY_HEADERS).',
    'const ASSET_HEADERS = Object.freeze({',
    ...h,
    '});',
    END,
  ].join('\n');
}

/** sw.js with its block replaced by `block`. */
export function withBlock(src, block) {
  const a = src.indexOf(BEGIN);
  const b = src.indexOf(END);
  if (a < 0 || b < a) throw new Error('public/sw.js has no GENERATED block');
  return src.slice(0, a) + block + src.slice(b + END.length);
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const src = readFileSync(SW, 'utf8');
  const next = withBlock(src, generatedBlock());
  if (process.argv.includes('--check')) {
    if (next !== src) {
      console.error('public/sw.js: the integrity manifest is out of date. Run: node tools/sw-manifest.mjs');
      process.exit(1);
    }
  } else if (next !== src) {
    writeFileSync(SW, next);
    console.log(`public/sw.js: ${Object.keys(buildManifest()).length} assets`);
  }
}
