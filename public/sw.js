// The content type a verified asset is served with, by extension.
const TYPES = {
  css: 'text/css; charset=utf-8', js: 'text/javascript; charset=utf-8', mjs: 'text/javascript; charset=utf-8',
  html: 'text/html; charset=utf-8', json: 'application/json', webmanifest: 'application/manifest+json',
  woff2: 'font/woff2', woff: 'font/woff', ttf: 'font/ttf', png: 'image/png', svg: 'image/svg+xml',
  ico: 'image/x-icon', wasm: 'application/wasm',
};
const hasOwn = (o, k) => Object.prototype.hasOwnProperty.call(o, k);

/** The SHA-256 this build lists for `path`, or null (such a path is never cached). */
function expectedHash(path) {
  return typeof path === 'string' && hasOwn(ASSET_SHA256, path) ? ASSET_SHA256[path] : null;
}

/** Base64 SHA-256 of `buf` (an ArrayBuffer). */
async function sha256(buf) {
  const d = new Uint8Array(await crypto.subtle.digest('SHA-256', buf));
  let s = '';
  for (let i = 0; i < d.length; i++) s += String.fromCharCode(d[i]);
  return btoa(s);
}

/** This build's headers for a verified asset at `path`. */
function headersFor(path) {
  const ext = path === '/' ? 'html' : (/\.([a-z0-9]+)$/i.exec(path) || [])[1];
  const h = new Headers(ASSET_HEADERS);
  h.set('content-type', (ext && TYPES[ext.toLowerCase()]) || 'application/octet-stream');
  h.set('cache-control', 'no-cache');
  return h;
}

/** Store `response` for `path` only when its body is the one this build lists. */
async function store(cache, key, path, response) {
  const expected = expectedHash(path);
  if (!expected || !isCacheableResponse(response)) return false;
  const body = await response.arrayBuffer();
  if ((await sha256(body)) !== expected) return false;
  await cache.put(key, new Response(body, { status: 200, headers: headersFor(path) }));
  return true;
}

/** A verified copy of `path` from the cache → a Response rebuilt with this build's headers, or null. */
async function verifiedFromCache(cache, key, path) {
  const expected = expectedHash(path);
  if (!expected) return null;
  const cached = await cache.match(key);
  if (!cached) return null;
  let body;
  try { body = await cached.arrayBuffer(); } catch { body = null; }
  if (!body || (await sha256(body)) !== expected) {
    await cache.delete(key).catch(() => {});
    return null;
  }
  return new Response(body, { status: 200, headers: headersFor(path) });
}

